    def get_all_questions(self):
        """إرجاع القائمة المنسدلة للأسئلة المتاحة ليتنقل بينها السائق"""
        return list(self.faq_list.keys())

    def get_answer(self, selected_question):
        """إرجاع الإجابة المعتمدة عند اختيار السائق لسؤال محدد"""
        timestamp = datetime.datetime.now().strftime("%H:%M")
        answer = self.faq_list.get(selected_question, "❌ السؤال غير مدرج في القائمة.")
        return {
            "question": selected_question,
            "answer": answer,
            "time": timestamp
        }

